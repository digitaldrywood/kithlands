function cloneLayout(source) {
  return {
    ...source,
    shell: { ...source.shell },
    header: {
      ...source.header,
      name: { ...source.header.name },
      position: { ...source.header.position },
      className: { ...source.header.className },
      previous: { ...source.header.previous },
      next: { ...source.header.next },
      loadout: { ...source.header.loadout },
    },
    portrait: { ...source.portrait },
    stats: { ...source.stats },
    equipment: {
      ...source.equipment,
      details: { ...source.equipment.details },
      socket: { ...source.equipment.socket },
      cardContent: { ...source.equipment.cardContent },
      cards: source.equipment.cards.map((card) => ({ ...card })),
      inspector: { ...source.equipment.inspector },
    },
    spells: { ...source.spells },
    close: { ...source.close },
  };
}

export function characterDetailLayout({
  viewportWidth = 800,
  viewportHeight = 600,
} = {}) {
  const source =
    viewportWidth <= 500 && viewportHeight > viewportWidth ? MOBILE : DESKTOP;
  return cloneLayout(source);
}
